// @ts-check
import { defineConfig } from 'astro/config';
import starlight from '@astrojs/starlight';
import sitemap from '@astrojs/sitemap';
import tailwindcss from '@tailwindcss/vite';
import { existsSync } from 'node:fs';
import { docsNav, docsSections } from './src/reference-nav.mjs';
import { GA_MEASUREMENT_ID, gaBootstrapScript } from './src/lib/analytics.mjs';

// Production origin. The real domain is the default so built pages carry
// correct canonical URLs; override with SITE_URL for local experiments.
const site = process.env.SITE_URL ?? 'https://cukededup.dev';
const ogImageUrl = new URL('/images/og.png', site).href;

// GA loads only in real production builds; the bootstrap script additionally
// gates itself on the served hostname at runtime.
const isBuild = process.argv.some((arg) => arg === 'build' || arg.endsWith('/build'));

const repoUrl = 'https://github.com/figueiredoluiz/cuke-dedup';
const generatedDocs = new URL('./src/content/docs/docs/', import.meta.url);

// Sidebar for the docs generated by scripts/sync-docs.mjs. Pages and folders absent at the
// synced release tag are left out.
const navItem = ({ file, label, children }) => {
  const slug = `docs/${file.replace(/\.md$/, '')}`;
  if (children && existsSync(new URL(`${children}/`, generatedDocs))) {
    return {
      label,
      items: [{ label: 'Overview', slug }, { autogenerate: { directory: `docs/${children}` } }],
    };
  }
  return { label, slug };
};

const docsSidebar = () => {
  const present = docsNav.filter(({ file }) => existsSync(new URL(file, generatedDocs)));
  const section = (name) => present.filter((entry) => entry.section === name).map(navItem);
  return [
    {
      label: 'Getting Started',
      items: [
        { label: 'Website home', link: '/' },
        { label: 'Introduction', slug: 'docs' },
      ],
    },
    ...docsSections.map((name) => ({
      label: name,
      items: [
        ...section(name),
        ...(name === 'Guides'
          ? [
              { label: 'Contributing', link: `${repoUrl}/blob/main/CONTRIBUTING.md` },
              { label: 'Changelog', link: '/changelog/' },
            ]
          : []),
      ],
    })),
  ];
};

// Routes of the former hand-written pages. The docs are generated from the release now, so these
// point to the page or section that covers the topic.
const rules = [
  'ambiguous-step',
  'duplicate-handler',
  'duplicate-matcher',
  'near-duplicate-step',
  'normalized-matcher',
  'overlapping-matcher',
  'parameterization-candidate',
  'unused-definition',
];
const redirects = {
  '/docs/installation': '/docs/#install',
  '/docs/quick-start': '/docs/#quick-start',
  '/docs/cli-reference': '/docs/configuration/',
  '/docs/understanding-results': '/docs/reports/',
  '/docs/troubleshooting': '/docs/safety-and-limitations/',
  '/docs/contributing': `${repoUrl}/blob/main/CONTRIBUTING.md`,
  '/docs/reference': '/docs/rules/',
  ...Object.fromEntries(rules.map((rule) => [`/docs/reference/${rule}`, `/docs/rules/#${rule}`])),
};

export default defineConfig({
  site,
  redirects,
  integrations: [
    starlight({
      title: 'CukeDedup',
      description:
        'A fast static analyzer for duplicate, ambiguous, reusable, and unused Cucumber/Gherkin step definitions.',
      logo: { src: './src/assets/icon.png' },
      favicon: '/favicon.png',
      customCss: ['./src/styles/starlight.css'],
      // Docs header matches the landing header: shared wordmark and icon
      // toggle instead of Starlight's default title and theme dropdown.
      components: {
        SiteTitle: './src/components/starlight/SiteTitle.astro',
        ThemeSelect: './src/components/starlight/ThemeSelect.astro',
      },
      social: [
        {
          icon: 'github',
          label: 'GitHub',
          href: 'https://github.com/figueiredoluiz/cuke-dedup',
        },
        {
          icon: 'npm',
          label: 'npm',
          href: 'https://www.npmjs.com/package/cuke-dedup',
        },
      ],
      head: [
        {
          tag: 'link',
          attrs: { rel: 'icon', type: 'image/png', sizes: '48x48', href: '/favicon.png' },
        },
        {
          tag: 'link',
          attrs: { rel: 'apple-touch-icon', sizes: '180x180', href: '/apple-touch-icon.png' },
        },
        {
          tag: 'meta',
          attrs: {
            property: 'og:image',
            content: ogImageUrl,
          },
        },
        {
          tag: 'meta',
          attrs: { property: 'og:image:width', content: '1200' },
        },
        {
          tag: 'meta',
          attrs: { property: 'og:image:height', content: '630' },
        },
        {
          tag: 'meta',
          attrs: {
            name: 'twitter:card',
            content: 'summary_large_image',
          },
        },
        ...(isBuild ? [{ tag: 'script', content: gaBootstrapScript(GA_MEASUREMENT_ID) }] : []),
      ],
      sidebar: docsSidebar(),
    }),
    sitemap(),
  ],
  vite: {
    plugins: [tailwindcss()],
  },
  markdown: {
    shikiConfig: {
      themes: {
        light: 'github-light',
        dark: 'github-dark',
      },
    },
  },
});
